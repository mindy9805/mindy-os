/** 以 id 取得來源，並自動補上 DOI 連結 */
export const referenceMap: Record<string, Reference> = Object.fromEntries(
  references.map((r) => [r.id, r.doi ? { ...r, url: r.url ?? doiUrl(r.doi) } : r]),
);

/** 依 id 清單取得來源（略過不存在的 id） */
export function getReferences(ids: string[]): Reference[] {
  return ids.map((id) => referenceMap[id]).filter(Boolean);
}

/** 格式化為 APA 風格的單行引用 */
export function formatCitation(r: Reference): string {
  return `${r.authors} (${r.year}). ${r.title}. ${r.source}.${r.doi ? ` https://doi.org/${r.doi}` : ''}`;
}
